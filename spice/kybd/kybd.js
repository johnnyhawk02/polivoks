// Keyboard board (sheet 3, У1) with the key string from sheet 1, in ngspice.
//   node spice/kybd/kybd.js dc     static voices for sets of held keys
//   node spice/kybd/kybd.js tran   gate, track-and-hold, voice 2 and glide
// The netlist is written to kb.cir next to this file.  See README.md.
const { execSync } = require('child_process'), fs = require('fs');
const mode = process.argv[2] || 'dc';
const NK = 48;                        // S1..S48, R1..R47 100 Ω (sheet 1)

// keys: list of {k, on, off} (key index 0 = S1, times in s; on = -1 for DC)
function netlist(keys, opts) {
  const L = [];
  L.push('* Polivoks keyboard board, sheet 3 (generated by kybd.js)');
  L.push('.include ../vco/ud8.lib');
  L.push('.model D521 D(IS=2n N=1.9 RS=5 CJO=1p TT=4n)');
  L.push('.model KT315G NPN(IS=2e-14 BF=150 VAF=100 IKF=0.1 CJE=7p CJC=7p TF=0.5n RB=40)');
  // КП303В: Idss 1.5..5 mA, cut-off -0.5..-3 V; middle values  EST
  L.push('.model KP303V NJF(VTO=-2 BETA=0.75m LAMBDA=0.02 IS=1e-14 CGS=6p CGD=2p)');
  L.push('.model SWK SW(VT=0.5 VH=0.1 RON=0.5 ROFF=1e12)');
  L.push('Vp vp 0 12.5', 'Vn vn 0 -12.5');
  const U = (n, p, m, o) => `X${n} ${p} ${m} vp vn ${o} UD8S r1=3.2g kc=0.1`;
  // A1 pilot oscillator: Schmitt R4 100k / R2 10k, R3 100k into C1 1000 pF
  if (opts.pilot) {
    L.push(U('A1', 'a1p', 'c1', 'a1o'), 'R3 a1o c1 100k', 'C1 c1 0 1000p', 'R4 a1o a1p 100k', 'R2 a1p 0 10k');
    L.push('R1 c1 a2p 100k', '.ic v(c1)=0.5 v(top)=0 v(c4)=0');
  }
  // A2 holds the top of the string at its (+) input; R5 10k sets 1.25 mA.
  // Reading: (+) = R1/R8 node, (-) = string top (see README)              EST
  L.push('R8 a2p 0 6.8k', 'R5 vp top 10k', U('A2', 'a2p', 'top', 'a2o'), 'R10 a2o bot 100');
  L.push('D4 0 top D521', 'D5 top 0 D521');
  // string: tap 0 = top (S1), tap 47 = bottom (S48)
  for (let i = 0; i < NK - 1; i++) L.push(`RS${i + 1} t${i} t${i + 1} 100`);
  L.push('Rtop top t0 0.01', `Rbot t${NK - 1} bot 0.01`);
  keys.forEach((s, j) => {
    if (s.on < 0) L.push(`RK${j} t${s.k} bus 0.5`);
    else {
      L.push(`SK${j} t${s.k} bus kc${j} 0 SWK`);
      L.push(`VK${j} kc${j} 0 PWL(0 0 ${s.on} 0 ${s.on + 1e-6} 1 ${s.off} 1 ${s.off + 1e-6} 0)`);
    }
  });
  L.push('Rleak bus 0 1g');
  // A3 offset (R6 trimmer): set to cancel the bottom of the string
  L.push(`VA3 a3o 0 ${opts.vofs}`);
  // A4: (bus-side voice 1) - (bottom) - (A3)
  L.push('R11 bot a4m 22.1k', 'R12 a3o a4m 22.1k', 'R13 a4o a4m 22.1k', 'C11 a4o a4m 0.01u');
  L.push('R16 v1 a4p 22.1k', 'R14 a4p 0 22.1k', 'R15 a4p 0 22.1k', U('A4', 'a4p', 'a4m', 'a4o'));
  if (opts.dc) {
    L.push('Ev1 v1 0 bus 0 1');       // DC: the hold follows the bus
  } else {
    // track-and-hold: R21 1k, C9 0.22u, V6 КП303В, C12 0.22u, A7 follower
    L.push('R21 bus c9 1k', 'C9 c9 0 0.22u', 'J6 c12 g6 c9 KP303V', 'C12 c12 0 0.22u');
    L.push(U('A7', 'c12', 'v1', 'v1'));
    // key detect: C5 1000p + R17 1k into A6 (R18 220k, R9 22.1k), C8/V1/V2,
    // R20 4.3k / C10 0.01u
    L.push('C5 bus a6i 1000p', 'R17 a6i a6m 1k', 'R9 a6m 0 22.1k', 'R18 a6o a6m 220k', U('A6', '0', 'a6m', 'a6o'));
    L.push('C8 a6o r1 0.01u', 'DV1 0 r1 D521', 'DV2 r1 det D521', 'R20 det 0 4.3k', 'C10 det 0 0.01u');
    // A8: (-) detector, (+) R22 13k / R23 820k from +12.5 → -12 V key pressed
    L.push('R23 vp a8p 820k', 'R22 a8p 0 13k', U('A8', 'a8p', 'det', 'gate'));
    // V7 КТ315Г: base on R27 100k (A8) / R28 16k (-12.5), collector R19 1M
    // to +12.5 and V3 КД521В to the gate of V6, which R29 10k bootstraps to A7
    L.push('R27 gate b7 100k', 'R28 b7 vn 16k', 'Q7 c7 b7 vn KT315G', 'R19 vp c7 1meg', 'DV3 g6 c7 D521', 'R29 v1 g6 10k');
    // glide: R24 1k + "Глиссандо" R48 (rheostat, 1 MΩ) into C4 0.22u to -12.5, A5
    L.push(`R24 v1 gl 1k`, `R48 gl c4 ${opts.rglide}`, 'C4 c4 vn 0.22u', U('A5', 'c4', 'cv1', 'cv1'));
    L.push('R25 gate x10 10k', 'Rx10 x10 0 100k');
  }
  return L;
}

function run(net, ctl) {
  fs.writeFileSync(__dirname + '/kb.cir', net.concat(['.control', ...ctl, '.endc', '.end']).join('\n') + '\n');
  return execSync('ngspice -b kb.cir 2>&1', { cwd: __dirname, maxBuffer: 1 << 26 }).toString();
}
const num = (out, n) => { const m = out.match(new RegExp('^' + n + '\\s*=\\s*([-0-9.e+]+)', 'm')); return m ? +m[1] : NaN; };

if (mode === 'dc') {
  // trim A3 first: one key at the top, voice 2 must equal voice 1
  const o0 = run(netlist([{ k: 0, on: -1 }], { dc: 1, vofs: 0 }), ['op', 'print v(top) v(bot) v(bus) v(a2o)']);
  const vbot = num(o0, 'v\\(bot\\)'), vofs = -vbot;
  console.log(`top ${num(o0, 'v\\(top\\)').toFixed(4)} V, bottom ${vbot.toFixed(4)} V, A2 out ${num(o0, 'v\\(a2o\\)').toFixed(3)} V; A3 trimmed to ${vofs.toFixed(4)} V`);
  const step = -vbot / (NK - 1);
  console.log(`string step ${(step * 1000).toFixed(2)} mV per key`);
  const cases = [[0], [12], [47], [5, 29], [29, 5], [0, 47], [10, 20, 30], [24, 25]];
  for (const ks of cases) {
    const o = run(netlist(ks.map(k => ({ k, on: -1 })), { dc: 1, vofs }), ['op', 'print v(bus) v(a4o) v(bot)']);
    const v1 = num(o, 'v\\(bus\\)'), v2 = num(o, 'v\\(a4o\\)');
    console.log(`keys ${JSON.stringify(ks).padEnd(12)} voice1 ${v1.toFixed(4)} V = key ${(-v1 / step).toFixed(3)}   voice2 ${v2.toFixed(4)} V = key ${(-v2 / step).toFixed(3)}   bottom ${num(o, 'v\\(bot\\)').toFixed(3)}`);
  }
} else {
  const vofs = +(process.env.VOFS || 5.875);
  const rg = process.env.RGLIDE || '100k';
  // key 5 at 2 ms; key 29 joins at 20 ms; key 5 lifts at 40 ms; key 29 at 60 ms;
  // key 17 alone at 80..100 ms; keys 10 and 40 together at 105..115 ms
  const keys = [{ k: 5, on: 2e-3, off: 40e-3 }, { k: 29, on: 20e-3, off: 60e-3 }, { k: 17, on: 80e-3, off: 100e-3 },
    { k: 10, on: 105e-3, off: 115e-3 }, { k: 40, on: 105e-3, off: 115e-3 }];
  const out = run(netlist(keys, { pilot: 1, vofs, rglide: rg }), [
    'tran 0.5u 0.125 0 0.5u uic',
    'meas tran ton  WHEN v(gate)=0 FALL=1 TD=1.9m',
    'meas tran toff WHEN v(gate)=0 RISE=1 TD=59m',
    'meas tran ton2 WHEN v(gate)=0 FALL=1 TD=79m',
    'meas tran tp1 WHEN v(a1o)=0 RISE=10', 'meas tran tp2 WHEN v(a1o)=0 RISE=110',
    'meas tran det  AVG v(det) from=10m to=19m',
    'meas tran pil  PP v(bus) from=10m to=11m',
    'meas tran a6pp PP v(a6o) from=10m to=11m',
    'meas tran v1a  AVG v(v1) from=18m to=19m',
    'meas tran v1b  AVG v(v1) from=38m to=39m',
    'meas tran v2b  AVG v(a4o) from=38m to=39m',
    'meas tran v1c  AVG v(v1) from=58m to=59m',
    'meas tran v2c  AVG v(a4o) from=58m to=59m',
    'meas tran v1d  AVG v(v1) from=75m to=79m',
    'meas tran v2d  AVG v(a4o) from=75m to=79m',
    'meas tran v1e  AVG v(v1) from=98m to=99m',
    'meas tran v1f  AVG v(v1) from=102m to=104m',
    'meas tran v1g  AVG v(v1) from=113m to=114m', 'meas tran v2g  AVG v(a4o) from=113m to=114m',
    'meas tran v1h  AVG v(v1) from=120m to=124m', 'meas tran v2h  AVG v(a4o) from=120m to=124m',
    'meas tran rip  PP v(v1) from=15m to=19m',
    'meas tran g1   AVG v(cv1) from=78m to=79m',
    // settling of voice 1 after the jump 29 -> 17 (V1 jumps from held 29 to 17)
    'let tgt = v1e',
    'meas tran ts50 WHEN v(v1)=-2.875 CROSS=1 TD=80m', 'meas tran ts99 WHEN v(v1)=-2.1375 CROSS=1 TD=80m',
    'meas tran tg50 WHEN v(cv1)=-2.875 CROSS=1 TD=80m',
    'meas tran g6off AVG v(g6) from=70m to=79m',
    'wrdata kb_tran.txt v(gate) v(v1) v(a4o) v(cv1)'
  ]);
  const g = (n) => num(out, n);
  const step = 0.125;
  console.log(`pilot ${(100 / (g('tp2') - g('tp1')) / 1000).toFixed(1)} kHz; on the bus ${(g('pil') * 1000).toFixed(1)} mV p-p, A6 out ${g('a6pp').toFixed(2)} V p-p, detector ${g('det').toFixed(2)} V`);
  console.log(`gate on ${((g('ton') - 2e-3) * 1e6).toFixed(0)} µs after the key, off ${((g('toff') - 60e-3) * 1e6).toFixed(0)} µs after the last key lifts, on again ${((g('ton2') - 80e-3) * 1e6).toFixed(0)} µs`);
  const k = (v) => (-v / step).toFixed(3);
  console.log(`key 5 alone: voice1 key ${k(g('v1a'))}, ripple ${(g('rip') * 1000).toFixed(2)} mV p-p`);
  console.log(`keys 5+29:   voice1 key ${k(g('v1b'))}, voice2 key ${k(g('v2b'))}`);
  console.log(`key 29 only: voice1 key ${k(g('v1c'))}, voice2 key ${k(g('v2c'))}`);
  console.log(`no keys (hold): voice1 key ${k(g('v1d'))}, voice2 key ${k(g('v2d'))}, V6 gate ${g('g6off').toFixed(2)} V`);
  console.log(`key 17: voice1 key ${k(g('v1e'))}; after release held at key ${k(g('v1f'))}`);
  console.log(`keys 10+40: voice1 key ${k(g('v1g'))}, voice2 key ${k(g('v2g'))}; both lifted together: voice1 key ${k(g('v1h'))}, voice2 key ${k(g('v2h'))}`);
  console.log(`hold before key 17: glide out key ${k(g('g1'))}`);
  console.log(`29→17 jump: voice1 half-way at ${((g('ts50') - 80e-3) * 1e6).toFixed(0)} µs, 1 % left (0.12 key) at ${((g('ts99') - 80e-3) * 1e6).toFixed(0)} µs, glide (R48 ${rg}) half-way at ${((g('tg50') - 80e-3) * 1e3).toFixed(2)} ms`);
}
